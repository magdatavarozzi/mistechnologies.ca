/* =========================================================
   ELEMENTS
   ========================================================= */

const languageToggle =
  document.getElementById("languageToggle");

const languageCurrent =
  document.getElementById("languageCurrent");

const languageOther =
  document.getElementById("languageOther");

const menuToggle =
  document.getElementById("menuToggle");

const navigation =
  document.getElementById("mainNav");

const contactForm =
  document.getElementById("contactForm");

const currentYear =
  document.getElementById("currentYear");


/* =========================================================
   CURRENT LANGUAGE
   ========================================================= */

let currentLanguage =
  localStorage.getItem("mistLanguage") || "en";

if (!translations[currentLanguage]) {
  currentLanguage = "en";
}


/* =========================================================
   TRANSLATION
   ========================================================= */

function translatePage(language) {

  const dictionary =
    translations[language];

  if (!dictionary) {
    return;
  }


  document.documentElement.lang =
    language;


  document.title =
    language === "fr"
      ? "MISTechnologies | Systèmes d’affaires et solutions numériques"
      : "MISTechnologies | Business Systems & Digital Solutions";


  document
    .querySelectorAll("[data-i18n]")
    .forEach((element) => {

      const key =
        element.dataset.i18n;

      if (
        Object.prototype.hasOwnProperty.call(
          dictionary,
          key
        )
      ) {
        element.innerHTML =
          dictionary[key];
      }

    });


  document
    .querySelectorAll("[data-i18n-html]")
    .forEach((element) => {

      const key =
        element.dataset.i18nHtml;

      if (
        Object.prototype.hasOwnProperty.call(
          dictionary,
          key
        )
      ) {
        element.innerHTML =
          dictionary[key];
      }

    });


  if (languageCurrent) {
    languageCurrent.textContent =
      language.toUpperCase();
  }


  if (languageOther) {
    languageOther.textContent =
      language === "en" ? "FR" : "EN";
  }


  if (languageToggle) {
    languageToggle.setAttribute(
      "aria-label",
      language === "en"
        ? "Changer la langue"
        : "Change language"
    );
  }


  localStorage.setItem(
    "mistLanguage",
    language
  );


  currentLanguage =
    language;


  if (menuToggle) {
    const isOpen =
      navigation &&
      navigation.classList.contains("open");

    menuToggle.setAttribute(
      "aria-label",
      isOpen
        ? (
            language === "fr"
              ? "Fermer la navigation"
              : "Close navigation"
          )
        : (
            language === "fr"
              ? "Ouvrir la navigation"
              : "Open navigation"
          )
    );
  }

}


/* =========================================================
   LANGUAGE TOGGLE
   ========================================================= */

function toggleLanguage() {

  translatePage(
    currentLanguage === "en"
      ? "fr"
      : "en"
  );

}


if (languageToggle) {

  languageToggle.addEventListener(
    "click",
    toggleLanguage
  );

}


/* =========================================================
   MOBILE NAVIGATION
   ========================================================= */

function closeNavigation() {

  if (!navigation || !menuToggle) {
    return;
  }


  navigation.classList.remove("open");

  menuToggle.setAttribute(
    "aria-expanded",
    "false"
  );

  menuToggle.setAttribute(
    "aria-label",
    currentLanguage === "fr"
      ? "Ouvrir la navigation"
      : "Open navigation"
  );

}


if (menuToggle && navigation) {

  menuToggle.addEventListener(
    "click",
    () => {

      const isOpen =
        navigation.classList.toggle("open");


      menuToggle.setAttribute(
        "aria-expanded",
        String(isOpen)
      );


      menuToggle.setAttribute(
        "aria-label",
        isOpen
          ? (
              currentLanguage === "fr"
                ? "Fermer la navigation"
                : "Close navigation"
            )
          : (
              currentLanguage === "fr"
                ? "Ouvrir la navigation"
                : "Open navigation"
            )
      );

    }
  );


  navigation
    .querySelectorAll("a")
    .forEach((link) => {

      link.addEventListener(
        "click",
        closeNavigation
      );

    });

}


/* =========================================================
   CONTACT FORM
   ========================================================= */

if (contactForm) {

  const formStatus =
    document.getElementById("formStatus");

  const formSubject =
    document.getElementById("formSubject");

  const submitButton =
    contactForm.querySelector('button[type="submit"]');


  const t = (key) =>
    (translations[currentLanguage] &&
      translations[currentLanguage][key]) || "";


  const showStatus = (key, state) => {

    if (!formStatus) return;

    formStatus.dataset.i18n = key;
    formStatus.textContent = t(key);
    formStatus.dataset.state = state;
    formStatus.hidden = false;

  };


  contactForm.addEventListener(
    "submit",
    async (event) => {

      event.preventDefault();


      const service =
        String(
          new FormData(contactForm).get("service") || ""
        ).trim();


      if (formSubject) {
        formSubject.value =
          currentLanguage === "fr"
            ? `Demande de renseignements — ${service || "MISTechnologies"}`
            : `Business inquiry — ${service || "MISTechnologies"}`;
      }


      const formData =
        new FormData(contactForm);


      if (submitButton) submitButton.disabled = true;

      showStatus("form.sending", "pending");


      try {

        const response =
          await fetch(contactForm.action, {
            method: "POST",
            body: formData,
            headers: { Accept: "application/json" }
          });


        if (response.ok) {

          contactForm.reset();
          showStatus("form.success", "success");

        } else {

          showStatus("form.error", "error");

        }

      } catch (error) {

        showStatus("form.error", "error");

      } finally {

        if (submitButton) submitButton.disabled = false;

      }

    }
  );

}


/* =========================================================
   CURRENT YEAR
   ========================================================= */

if (currentYear) {

  currentYear.textContent =
    new Date().getFullYear();

}


/* =========================================================
   SCROLL REVEAL
   ========================================================= */

const revealElements =
  document.querySelectorAll(".reveal");


if (
  "IntersectionObserver" in window
) {

  const revealObserver =
    new IntersectionObserver(
      (entries, observer) => {

        entries.forEach((entry) => {

          if (entry.isIntersecting) {

            entry.target.classList.add(
              "visible"
            );

            observer.unobserve(
              entry.target
            );

          }

        });

      },
      {
        threshold: 0.12
      }
    );


  revealElements.forEach(
    (element) => {

      revealObserver.observe(
        element
      );

    }
  );

} else {

  revealElements.forEach(
    (element) => {

      element.classList.add(
        "visible"
      );

    }
  );

}


/* =========================================================
   INITIALIZE
   ========================================================= */

translatePage(
  currentLanguage
);
